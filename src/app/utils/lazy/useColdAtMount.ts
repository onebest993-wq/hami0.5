import { useState } from 'react';

/**
 * هل كانت الوحدةُ باردةً لحظةَ تركيب هذا المكوّن؟ — يُحسب مرّةً ويُثبَّت ما عاش المكوّن.
 *
 * **العطلُ الذي يمنعه:** `isPreloaded() ? <X/> : <Suspense>…<X/></Suspense>` إذا قُيِّم في كلّ
 * رسم، فمكوّنٌ رُكّب بارداً يعرض `X` داخل `Suspense`، ثمّ يكتمل التحميل، **فأوّلُ إعادة رسمٍ
 * بعدها** تُرجع `X` بلا `Suspense` — نوعُ عنصرٍ آخر في الموضع نفسه، **فيهدم React كلَّ ما تحته
 * ويُعيد تركيبه**: كلُّ حالةٍ تعود إلى قيمتها الأولى **بلا أيّ setter**، ويُعاد كلُّ ما يعمل
 * عند التركيب. قِيس في E2E: مركزُ القرارات يُهدم ويُركَّب بعد ضغط «القرارات السابقة» فيضيع
 * الضغط، والإضبارةُ كلُّها تُهدم حين يكتمل تحميلُ بوّابتها بعد فتحها.
 *
 * **والتثبيتُ لا يُعيد الوميضَ الذي أُريد تجنّبُه:** `createPreloadableLazyComponent` يرسم
 * المكوّنَ المحمَّل مباشرةً، فـ`Suspense` حول مكوّنٍ محمَّل لا يعلّق ولا يُظهر بديله.
 *
 * يُمرَّر الفحصُ دالّةً لا قيمة: يُستدعى مرّةً واحدة، عند التركيب.
 */
export function useColdAtMount(isPreloaded: () => boolean): boolean {
    const [coldAtMount] = useState(() => !isPreloaded());
    return coldAtMount;
}
