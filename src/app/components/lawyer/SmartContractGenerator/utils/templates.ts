export interface ShieldArticleTemplate {
    id: string;
    content: string;
}

export function buildShieldArticle(
    id: string,
    articleNumber: number,
    shockPercentage?: number
): ShieldArticleTemplate {
    switch (id) {
        case 'evidentiary':
            return {
                id: 'evidentiary',
                content: `المادة (${articleNumber}) - الحجية الرقمية: يُقر الطرفان إقراراً مانعاً للرجوع بأن كافة المراسلات عبر البريد الإلكتروني أو تطبيق (WhatsApp) المعتمدة في تنفيذ هذا العقد، تُعد حجة كتابية قاطعة، وتسري عليها أحكام السند العادي وفق قانون الإثبات العراقي، ويسقط حقهما في الطعن بصحتها أو المطالبة باستكتابها.`
            };
        case 'guillotine':
            return {
                id: 'guillotine',
                content: `المادة (${articleNumber}) - الشرط الفاسخ الصريح: يُعد هذا العقد مفسوخاً من تلقاء نفسه، وبقوة القانون، بمجرد إخلال أي من الطرفين بالتزاماته الجوهرية، وذلك دون حاجة إلى تنبيه، أو إنذار عن طريق الكاتب العدل، أو استصدار حكم قضائي تطبيقاً للمادة (178) من القانون المدني العراقي، وتُعد يد الطرف المخل على محل العقد يد غاصب تبيح اتخاذ كافة الإجراءات المستعجلة لطرده.`
            };
        case 'shockAbsorption':
            return {
                id: 'shockAbsorption',
                content: `المادة (${articleNumber}) - استقرار الالتزامات والظروف الطارئة: يتنازل الطرفان مسبقاً عن حق المطالبة بتعديل الالتزامات استناداً لنظرية الظروف الطارئة (المادة 146 مدني)، ويُقران بأن أي تذبذب مالي في أسعار الصرف أو تضخم اقتصادي لا يتجاوز نسبة [ ${shockPercentage ?? 15}% ] يُعد من المخاطر التجارية المتوقعة التي ارتضياها وقت التعاقد، ولا يجوز التذرع بها لفسخ العقد أو تعديله.`
            };
        default:
            return { id, content: '' };
    }
}

