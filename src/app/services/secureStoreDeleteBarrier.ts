/**
 * حاجز الحذف — يمنع كتابةً أُطلقت قبل الحذف من الهبوط بعده فتُحييه.
 *
 * ## العطل الذي وُجد له
 *
 * `setItemSync` يجدول كتابة دائمة ولا ينتظرها. فإن حُذف المفتاح قبل هبوطها،
 * تُنفَّذ الكتابة **بعد** الحذف فتُعيد كتابة القيمة المحذوفة. الحذف نفسه سليم —
 * يمسح الكاش المفكوك والمخزن الاحتياطي وIndexedDB — ثم تأتي الكتابة فتنقض الثلاثة.
 *
 * مقيس لا مستنتَج:
 *
 *     setItemSync('A', v);  await deleteItem('A');
 *     getItemSync('A')                →  null   ✅ الحذف وقع
 *     await tick(); getItemSync('A')  →  v      ❌ ثم عاد
 *
 * وضابطان يعزلان السبب في طابور الكتابة وحده: `await waitForPendingSetItem('A')`
 * قبل الحذف يمنع العودة، وكذلك مجرّد `await tick()` — كلاهما يُهبط الكتابة أولاً.
 * و`deleteItemSync` كان مصاباً بالعطل نفسه.
 *
 * **الأثر:** محامٍ يعدّل إضبارة ثم يحذفها في اللحظة التالية — فتعود بعد لحظة بلا
 * رسالة. وحذفٌ لا يثبت في تطبيق أسرار مهنية فقدانُ سيطرةٍ على البيانات، لا إزعاج.
 *
 * ## الآلية
 *
 * عدّاد **عام** واحد يتصاعد مع كل حذف. يسجّل الحذف قيمته الجديدة لمفتاحه، وتلتقط
 * كل كتابة القيمة المسجَّلة لمفتاحها عند بدئها، ثم تقارن قبل الالتزام: إن صار
 * المسجَّل **أكبر**، فقد وقع حذفٌ بينهما فتُسقط الكتابة نفسها.
 *
 * ## لماذا `>` لا `!==` — وهو ما يجعل الحاجز آمناً بلا تسجيل
 *
 * المقارنة بالتفاوت تُلزمنا بمعرفة أيّ كتابة طائرة الآن، كي لا نمسح مدخلاً تنتظره
 * كتابة فتقرأ صفراً مخالفاً لما التقطته فتُسقط نفسها **بلا حذفٍ وقع** — أي فقدان
 * بيانات صامت. ومعرفة ذلك تقتضي عدّاداً يُزاد عند الدخول ويُنقَص عند الخروج، و
 * `setItem` لها تسعة مخارج، فالعدّاد يفرض `try/finally` حول جسدها كلّه.
 *
 * والتصاعد العام يُغني عن ذلك: الأرقام لا تتكرّر ولا تتناقص، فغياب المدخل يعني
 * صفراً، و`0 > N` كاذبة دائماً. **فأسوأ ما يُنتجه الغياب إسقاطٌ فائت لا إسقاط
 * كاذب** — ولهذا لا تحتاج هذه الوحدة أن تعرف شيئاً عن طابور الكتابة، وتغطّي كل
 * كاتب: الطابور، و`setItem` المباشرة، وأيّ مستدعٍ يُضاف لاحقاً.
 *
 * ## حدّ النمو — بالزمن لا بالعدد، وهذا تصحيح لخطأ سابق
 *
 * كان الحدّ `256` مدخلاً بإزاحة الأقدم، وكُتب هنا أن بلوغه «غير واقعي» وأن نتيجته
 * «إسقاط فائت لا إتلاف». **وكلا العبارتين خطأ، وقِيس:**
 *
 *     setItem('victim')  ← تلتقط الجيل ثم تنتظر
 *     deleteItemSync('victim')            ← الجيل يُسجَّل
 *     ٣٠٠ حذف لمفاتيح أخرى                ← مدخل victim يُزاح
 *     await الكتابة  ⇒  getItemSync('victim') = '{"x":1}'   ❌ عاد المحذوف
 *
 * والضابط (حذف واحد بدل ٣٠٠) يبقى `null`. أمّا «غير واقعي» فمحوُ الحساب و«امسح
 * كل بياناتي» يحذفان **كل مفتاح على الجهاز** في نبضة واحدة — إضابير التنفيذ وحدها
 * مفتاحٌ لكل ملف — فتجاوز ٢٥٦ هو الحالة العادية هناك لا النادرة. وأمّا «لا إتلاف»
 * فالنتيجة عودةُ مفتاح حُذف أثناء «امسح بياناتي»، وهو إتلافٌ للسرّية بالمعيار
 * الذي قِيس به الحذف نفسه: حذف الإضبارة فعلُ سرّية مهنية.
 *
 * فالحدّ صار **زمنياً**: يُحتفظ بالمدخل ما دام سباقُه ممكناً (`ENTRY_TTL_MS`)،
 * والخريطة مرتَّبة بالإدراج فالتقليم يمسّ مقدّمتها وحدها — بلا مسحٍ كامل مع كل
 * حذف. ونافذة الكتابة (التقاط الجيل ← الالتزام) أجزاء من الثانية على الجهاز، فمهلةٌ
 * بدقيقة تسعها بفارق أضعاف.
 *
 * ويبقى سقف صلب (`HARD_MAX_TRACKED_KEYS`) لحالة لا تقع في هذا التطبيق: أكثر من
 * عشرين ألف حذف داخل الدقيقة الواحدة. وعنده وحده تعود الإزاحة بالأقدم — **وهذا هو
 * المسار الوحيد الذي يُفقد فيه الحاجز مدخلاً**، ويُذكر صراحةً بدل أن يُوصف بأنه
 * لا يقع.
 *
 * ## تسلسل set → delete → set يبقى صحيحاً
 *
 * الأولى التقطت رقماً أقدم فتُسقط، والثانية التقطت المسجَّل بعد الحذف فتُنفَّذ.
 *
 * التفصيل الكامل ومسار التشخيص: `hami-audit/FINDING-012` و`FINDING-014`.
 */

/** مهلة بقاء المدخل: نافذة السباق أجزاء من الثانية، وهذه دقيقة كاملة */
const ENTRY_TTL_MS = 60_000;
/** سقف صلب لحالة لا تقع هنا — وهو المسار الوحيد الذي يُفقد فيه مدخل */
const HARD_MAX_TRACKED_KEYS = 20_000;

type DeleteMark = { gen: number; at: number };

const keyDeleteGeneration = new Map<string, DeleteMark>();
let deleteCounter = 0;

/**
 * تقليم المقدّمة وحدها: `Map` ترتّب بالإدراج، و`markKeyDeleted` يحذف ثم يُدرج
 * فتصير مرتّبة بالأحدث. فالمنتهية مهلتها كلّها في المقدّمة، والتقليم يقف عند أوّل
 * مدخل حيّ — فكلفته بعدد ما يُقلَّم لا بحجم الخريطة.
 */
function pruneExpired(now: number): void {
    for (const [key, mark] of keyDeleteGeneration) {
        if (now - mark.at <= ENTRY_TTL_MS) break;
        keyDeleteGeneration.delete(key);
    }
}

/** يسجّل للمفتاح رقماً أكبر من أيّ رقم سابق، فتُسقط الكتابات التي التقطت ما قبله */
export function markKeyDeleted(key: string): void {
    const now = Date.now();
    deleteCounter += 1;
    keyDeleteGeneration.delete(key);
    keyDeleteGeneration.set(key, { gen: deleteCounter, at: now });
    pruneExpired(now);
    while (keyDeleteGeneration.size > HARD_MAX_TRACKED_KEYS) {
        const oldest = keyDeleteGeneration.keys().next();
        if (oldest.done) break;
        keyDeleteGeneration.delete(oldest.value);
    }
}

/** رقم آخر حذف للمفتاح — تلتقطه الكتابة عند بدئها وتقارنه قبل الالتزام */
export function readDeleteGeneration(key: string): number {
    return keyDeleteGeneration.get(key)?.gen ?? 0;
}
