/**
 * حاجز الحذف — يمنع كتابةً أُطلقت قبل الحذف من الهبوط بعده فتُحييه.
 *
 * ## العطل الذي وُجد له
 *
 * `setItemSync` يجدول كتابة دائمة ولا ينتظرها. فإن حُذف المفتاح قبل هبوطها،
 * تُنفَّذ الكتابة **بعد** الحذف فتُعيد كتابة القيمة المحذوفة. الحذف نفسه سليم —
 * يمسح الكاش المفكوك والمخزن الاحتياطي وIndexedDB — ثم تأتي الكتابة فتنقض الثلاثة.
 *
 * مقيس لا مستنتَج:
 *
 *     setItemSync('A', v);  await deleteItem('A');
 *     getItemSync('A')                →  null   ✅ الحذف وقع
 *     await tick(); getItemSync('A')  →  v      ❌ ثم عاد
 *
 * وضابطان يعزلان السبب في طابور الكتابة وحده: `await waitForPendingSetItem('A')`
 * قبل الحذف يمنع العودة، وكذلك مجرّد `await tick()` — كلاهما يُهبط الكتابة أولاً.
 * و`deleteItemSync` كان مصاباً بالعطل نفسه.
 *
 * **الأثر:** محامٍ يعدّل إضبارة ثم يحذفها في اللحظة التالية — فتعود بعد لحظة بلا
 * رسالة. وحذفٌ لا يثبت في تطبيق أسرار مهنية فقدانُ سيطرةٍ على البيانات، لا إزعاج.
 *
 * ## الآلية
 *
 * لكل مفتاح **جيل**. تلتقط كل كتابة جيلَ مفتاحها وقت جدولتها، وتُسقط نفسها إن
 * تغيّر الجيل قبل تنفيذها. والحذف يرفع الجيل.
 *
 * وهذا يغطّي الكتابة **المجدولة التي لم تبدأ**. أمّا التي **بدأت فعلاً** فقد
 * تجاوزت نقطة الفحص، فيتولّاها `deleteItem` بانتظار الكتابة الطائرة قبل الحذف.
 * الحاجزان معاً يجعلان الحذف نهائياً.
 *
 * ## لماذا لا ينمو بلا حدّ
 *
 * لا يُسجَّل جيل إلا وهناك كتابة معلّقة فعلاً (`hasPendingWrite`)، ويُمسح مع آخر
 * كتابة تنتهي. فالخريطة لا تحمل إلا مفاتيح لها كتابة طائرة الآن.
 *
 * ## تسلسل set → delete → set يبقى صحيحاً
 *
 * الكتابة الأولى تُسقَط (تغيّر الجيل)، والثانية التقطت الجيل الجديد فتُنفَّذ.
 *
 * التفصيل الكامل ومسار التشخيص: `hami-audit/FINDING-012`.
 */

const keyDeleteGeneration = new Map<string, number>();

/**
 * يرفع جيل المفتاح فتُسقط الكتابات المجدولة قبله.
 *
 * `hasPendingWrite` يُمرَّر من المستدعي بدل استيراد طابور الكتابة هنا — يبقي هذه
 * الوحدة بلا تبعيات، ويمنع تسجيل جيل لا كتابة تنتظره (فيُسرّب ذاكرة بلا فائدة).
 */
export function markKeyDeleted(key: string, hasPendingWrite: boolean): void {
    if (!hasPendingWrite) return;
    keyDeleteGeneration.set(key, (keyDeleteGeneration.get(key) ?? 0) + 1);
}

/** جيل المفتاح الآن — تلتقطه الكتابة عند الجدولة وتقارنه عند التنفيذ */
export function readDeleteGeneration(key: string): number {
    return keyDeleteGeneration.get(key) ?? 0;
}

/** تُستدعى مع انتهاء آخر كتابة معلّقة للمفتاح */
export function clearDeleteGeneration(key: string): void {
    keyDeleteGeneration.delete(key);
}
