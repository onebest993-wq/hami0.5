/**
 * Sync production security headers from TypeScript SoT → vercel.json + public/_headers.
 * Usage:
 *   node scripts/sync-security-headers.mjs           # write
 *   node scripts/sync-security-headers.mjs --check   # fail on drift
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const checkOnly = process.argv.includes('--check');

function loadProductionHeaders() {
  const tmp = path.join(ROOT, '.cursor', '_sync-security-headers-loader.mts');
  fs.mkdirSync(path.dirname(tmp), { recursive: true });
  fs.writeFileSync(
    tmp,
    `import { getProductionSecurityHeaders } from '../src/app/api/security/wifeSecurityHeaders.ts';\n` +
      `process.stdout.write(JSON.stringify(getProductionSecurityHeaders()));\n`,
    'utf8',
  );
  try {
    const r = spawnSync(
      process.execPath,
      [path.join(ROOT, 'node_modules', 'vite-node', 'vite-node.mjs'), tmp],
      { cwd: ROOT, encoding: 'utf8', env: { ...process.env, NODE_ENV: 'production' } },
    );
    if (r.status !== 0) {
      throw new Error((r.stderr || r.stdout || 'vite-node failed').trim());
    }
    const out = (r.stdout || '').trim();
    const jsonStart = out.lastIndexOf('{');
    if (jsonStart < 0) throw new Error(`unexpected vite-node output: ${out.slice(0, 200)}`);
    return JSON.parse(out.slice(jsonStart));
  } finally {
    try {
      fs.unlinkSync(tmp);
    } catch {
      /* ignore */
    }
  }
}

function renderNetlifyHeaders(headers) {
  const lines = [
    '# Netlify / static — أمان الإنتاج + cache (CSP = contentSecurityPolicy production)',
    '# AUTO-GENERATED by scripts/sync-security-headers.mjs — do not hand-edit header values.',
    '/*',
  ];
  for (const [key, value] of Object.entries(headers)) {
    lines.push(`  ${key}: ${value}`);
  }
  lines.push(
    '',
    '/index.html',
    '  Cache-Control: no-cache',
    '',
    '/assets/*',
    '  Cache-Control: public, max-age=31536000, immutable',
    '',
    '/static-law-data/manifest.json',
    '  Cache-Control: no-cache',
    '',
    '/static-law-data/v1/*',
    '  Cache-Control: public, max-age=31536000, immutable',
    '',
  );
  return `${lines.join('\n')}`;
}

function syncVercel(headers) {
  const vercelPath = path.join(ROOT, 'vercel.json');
  const vercel = JSON.parse(fs.readFileSync(vercelPath, 'utf8'));
  const securityBlock = vercel.headers?.find((h) => h.source === '/(.*)');
  if (!securityBlock) throw new Error('vercel.json missing /(.*) headers block');
  const nextHeaders = Object.entries(headers).map(([key, value]) => ({ key, value }));
  const keep = (securityBlock.headers || []).filter((h) => !(h.key in headers));
  securityBlock.headers = [...nextHeaders, ...keep];
  const next = `${JSON.stringify(vercel, null, 2)}\n`;
  const prev = fs.readFileSync(vercelPath, 'utf8');
  return { path: vercelPath, prev, next, changed: prev !== next };
}

function syncNetlify(headers) {
  const headersPath = path.join(ROOT, 'public', '_headers');
  const next = renderNetlifyHeaders(headers);
  const prev = fs.existsSync(headersPath) ? fs.readFileSync(headersPath, 'utf8') : '';
  // Normalize trailing newline comparison
  const norm = (s) => s.replace(/\r\n/g, '\n').replace(/\n+$/, '\n');
  return { path: headersPath, prev, next, changed: norm(prev) !== norm(next) };
}

const headers = loadProductionHeaders();
const jobs = [syncVercel(headers), syncNetlify(headers)];
let drift = false;
for (const job of jobs) {
  if (!job.changed) {
    console.log(`[sync-security-headers] OK ${path.relative(ROOT, job.path)} (in sync)`);
    continue;
  }
  drift = true;
  if (checkOnly) {
    console.error(`[sync-security-headers] DRIFT ${path.relative(ROOT, job.path)}`);
  } else {
    fs.writeFileSync(job.path, job.next.replace(/\n+$/, '\n'), 'utf8');
    console.log(`[sync-security-headers] WROTE ${path.relative(ROOT, job.path)}`);
  }
}

if (checkOnly && drift) {
  console.error('[sync-security-headers] FAIL — run: npm run sync:security-headers');
  process.exit(1);
}
console.log(`[sync-security-headers] ${checkOnly ? 'CHECK OK' : 'SYNC OK'}`);
